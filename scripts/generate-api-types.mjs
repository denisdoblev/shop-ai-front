import nextEnv from "@next/env";
import openapiTS, { astToString } from "openapi-typescript";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const projectDir = fileURLToPath(new URL("..", import.meta.url));
const { loadEnvConfig } = nextEnv;
loadEnvConfig(projectDir);

const backendUrl = process.env.BACKEND_URL;

if (!backendUrl) {
  throw new Error(
    "BACKEND_URL is required. Copy .env.example to .env.local before generating API types.",
  );
}

const schemaUrl = new URL("api/docs-json", `${backendUrl.replace(/\/$/, "")}/`);
const outputPath = new URL("../lib/api/generated.ts", import.meta.url);
const ast = await openapiTS(schemaUrl);
const contents = `// Generated by pnpm api:types. Do not edit manually.\n${astToString(ast)}\n`;

await writeFile(outputPath, contents, "utf8");

console.log(`Generated ${fileURLToPath(outputPath)} from ${schemaUrl}`);
